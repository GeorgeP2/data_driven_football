"""How good is each team, and how hard is each fixture?

Two numbers per team: an attack rating (goals they tend to score) and a defence rating (goals
they tend to concede), both relative to the league average. A fixture's difficulty then falls
out of the pairing — a good attack against a poor defence expects a lot of goals — which is what
turns "Haaland is good" into "Haaland is good *this week*".

Everything here is built from completed gameweeks only, and shrunk toward the league mean. The
shrinkage matters: after two gameweeks a team that has conceded five is not really the worst
defence in history, and a model that believes it will chase noise all season. Early on the
ratings stay close to average and only separate as evidence accumulates.
"""

from __future__ import annotations

import math
from collections.abc import Sequence
from dataclasses import dataclass

from fpl_optimiser.backtest.history import GameweekRecord

PRIOR_MATCHES = 6.0
"""Weight of the "everyone is average" prior, in matches. A team needs roughly this many games
before its own record outweighs the assumption that it is ordinary. Six is about a sixth of a
season — responsive enough to notice a good side, slow enough to ignore a fluke."""

HOME_ADVANTAGE = 1.15
"""Home teams score about 15% more. A well-established effect, and cheap to include."""

DEFAULT_GOALS_PER_MATCH = 1.4
"""Expected goals a team generates in an average Premier League match. Used before any evidence
exists."""

LEAGUE_PRIOR_MATCHES = 20.0
"""How strongly the league-average goal rate is anchored to its long-run value. Without this
the mean is derived from the same handful of matches it is meant to calibrate, which is
circular and makes the opening weeks of a season meaningless."""


@dataclass(frozen=True)
class TeamRatings:
    """Attack and defence ratings, as goals per match, shrunk toward the league mean."""

    attack: dict[int, float]
    defence: dict[int, float]
    league_mean: float

    def _rating(self, ratings: dict[int, float], team_id: int) -> float:
        # An unseen team (newly promoted, or a mid-season data gap) is assumed average rather
        # than raising: the caller cannot do anything useful with an exception here.
        return ratings.get(team_id, self.league_mean)

    def expected_goals(
        self, team_id: int, opponent_id: int, *, at_home: bool
    ) -> tuple[float, float]:
        """Goals this team is expected to score and concede against this opponent.

        Attack and defence are combined multiplicatively and normalised by the league mean, so a
        league-average attack facing a league-average defence expects exactly the league mean.
        """
        attack = self._rating(self.attack, team_id)
        defence = self._rating(self.defence, team_id)
        opponent_attack = self._rating(self.attack, opponent_id)
        opponent_defence = self._rating(self.defence, opponent_id)

        home = HOME_ADVANTAGE if at_home else 1.0
        away = 1.0 if at_home else HOME_ADVANTAGE

        scored = attack * (opponent_defence / self.league_mean) * home
        conceded = defence * (opponent_attack / self.league_mean) * away
        return scored, conceded

    def clean_sheet_probability(self, team_id: int, opponent_id: int, *, at_home: bool) -> float:
        """Probability of conceding nothing, as Poisson(0) on the expected goals against.

        Goals are close enough to Poisson for this purpose, and a clean sheet is worth 4 points
        to a defender — enough that getting this roughly right matters more than getting it
        exactly right.
        """
        _, conceded = self.expected_goals(team_id, opponent_id, at_home=at_home)
        return math.exp(-conceded)


def _team_matches(
    records: Sequence[GameweekRecord],
) -> dict[int, list[tuple[float, float]]]:
    """Each team's (expected goals for, expected goals against) per match.

    **Expected goals, not actual goals.** A team that won 4-0 may have been fortunate; a team that
    lost 0-1 having created chance after chance is not really a poor attack. Actual goals are the
    noisiest signal available, and rating teams on them means the model spends the first third of
    every season chasing scorelines.

    Two conveniences make this cheap. A team's xG is simply the *sum of its players' xG*, which is
    already in the archive. And a team's expected goals **conceded** needs no separate field at
    all: it is whatever the opposition generated in the same fixture. That makes attack and
    defence two views of one number, and internally consistent by construction.
    """
    # xG generated by each side of each match, keyed so the two halves can find each other.
    generated: dict[tuple[int, int, int], float] = {}
    for record in records:
        for fixture in record.opponents:
            key = (record.gameweek, record.team_id, fixture.opponent_team_id)
            generated[key] = generated.get(key, 0.0) + record.expected_goals

    matches: dict[int, list[tuple[float, float]]] = {}
    for (gameweek, team_id, opponent_id), expected_for in generated.items():
        # What the opposition created in this same fixture is exactly what we expected to concede.
        expected_against = generated.get((gameweek, opponent_id, team_id))
        if expected_against is None:
            # One side of the fixture is missing from the records — nothing sane to infer.
            continue
        matches.setdefault(team_id, []).append((expected_for, expected_against))
    return matches


def build_ratings(
    completed: Sequence[GameweekRecord],
    *,
    previous_season: Sequence[GameweekRecord] = (),
) -> TeamRatings:
    """Rate every team from completed matches, shrinking toward the league mean.

    Last season's record supplies the prior where this season has little to go on, which is what
    stops the opening gameweeks being decided by noise.
    """
    current = _team_matches(completed)
    prior = _team_matches(previous_season)

    played = [m for team_matches in current.values() for m in team_matches]

    # The league mean must itself be shrunk, or it is circular: with two gameweeks played it is
    # computed from the very matches it is then used to judge, so a high-scoring opening weekend
    # convinces the model that 3 goals a game is normal and nothing looks unusual. Anchoring it
    # to the long-run Premier League average keeps early-season ratings sane.
    total_goals = sum(expected_for for expected_for, _ in played)
    league_mean = (total_goals + DEFAULT_GOALS_PER_MATCH * LEAGUE_PRIOR_MATCHES) / (
        len(played) + LEAGUE_PRIOR_MATCHES
    )
    if league_mean <= 0:
        league_mean = DEFAULT_GOALS_PER_MATCH

    def prior_rates(team_id: int) -> tuple[float, float]:
        """Last season's expected-goal rates, or the league mean if unknown."""
        history = prior.get(team_id, [])
        if not history:
            return league_mean, league_mean
        scored = sum(expected_for for expected_for, _ in history) / len(history)
        conceded = sum(against for _, against in history) / len(history)
        return scored, conceded

    attack: dict[int, float] = {}
    defence: dict[int, float] = {}
    for team_id in set(current) | set(prior):
        matches = current.get(team_id, [])
        prior_attack, prior_defence = prior_rates(team_id)

        # Shrinkage: the prior counts for PRIOR_MATCHES games, this season's record for the
        # games actually played. Early on the prior dominates; by spring it is irrelevant.
        weight = len(matches)
        scored = sum(expected_for for expected_for, _ in matches)
        conceded = sum(against for _, against in matches)

        attack[team_id] = (scored + prior_attack * PRIOR_MATCHES) / (weight + PRIOR_MATCHES)
        defence[team_id] = (conceded + prior_defence * PRIOR_MATCHES) / (weight + PRIOR_MATCHES)

    return TeamRatings(attack=attack, defence=defence, league_mean=league_mean)
